export function isRealDate(value: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00.000Z`);
  return Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

export function nairobiToday() {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Africa/Nairobi",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(new Date());
  const value = (type: string) => parts.find((part) => part.type === type)?.value ?? "00";
  return `${value("year")}-${value("month")}-${value("day")}`;
}

export function addNairobiDays(days: number) {
  const date = new Date(`${nairobiToday()}T00:00:00.000Z`);
  date.setUTCDate(date.getUTCDate() + days);
  return date.toISOString().slice(0, 10);
}

export function isFutureNairobiSlot(date: string, time: string) {
  if (!isRealDate(date) || !/^\d{2}:\d{2}$/.test(time)) return false;
  const timestamp = new Date(`${date}T${time}:00+03:00`).getTime();
  return Number.isFinite(timestamp) && timestamp > Date.now();
}
